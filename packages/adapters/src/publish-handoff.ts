/**
 * Как расширение узнаёт, КАКОЙ объект размещают.
 *
 * ЗАДАЧА. Агент открывает на площадке форму «новое объявление». Объектов
 * у него сорок, а форма одна и про них ничего не знает. Заполнять её нечем,
 * пока расширение не выяснит, о котором речь.
 *
 * РЕШЕНИЕ — МЕТКА В ЯКОРЕ АДРЕСА. Кнопка «Разместить» на карточке открывает
 * форму сама и дописывает к адресу `#kleekto=<идентификатор>`. Расширение
 * читает его на странице.
 *
 * ПОЧЕМУ ИМЕННО ЯКОРЬ, А НЕ ПАРАМЕТР ЗАПРОСА. Якорь НЕ УХОДИТ НА СЕРВЕР
 * площадки: браузер его не отправляет вовсе. То есть ss.ge не получает
 * ни одного нашего идентификатора и вообще не узнаёт, что тут замешана
 * чужая система. Параметр `?kleekto=…` попал бы в их журналы, аналитику
 * и, возможно, в ссылку на созданное объявление.
 *
 * Идентификатор объекта — не секрет и не персональные данные: он ничего
 * не открывает без сессии. Но отдавать площадке даже его незачем.
 */

/** Имя метки. Своё, чтобы не столкнуться с якорями самой площадки. */
const MARK = 'kleekto';

/** UUID и ничего кроме: в адресную строку пишет кто угодно. */
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/iu;

/** Адрес формы с меткой объекта. */
export function withPropertyMark(formUrl: string, propertyId: string): string {
  return `${formUrl}#${MARK}=${encodeURIComponent(propertyId)}`;
}

/**
 * Идентификатор объекта из адреса страницы, либо `null`.
 *
 * Значение ПРОВЕРЯЕТСЯ ПО ФОРМЕ, а не берётся как есть: якорь правит кто
 * угодно, а дальше он уходит в запрос к нашему серверу. Сервер, конечно,
 * проверит права сам, но отправлять туда произвольную строку из адресной
 * строки чужого сайта незачем.
 */
export function propertyMark(url: string): string | null {
  let hash: string;
  try {
    hash = new URL(url).hash;
  } catch {
    return null;
  }

  if (hash === '') return null;

  const value = new URLSearchParams(hash.replace(/^#/u, '')).get(MARK);
  if (value === null) return null;

  return UUID.test(value) ? value : null;
}

