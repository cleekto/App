import type { FillResult, ListingPublishDraft, PublishedRef } from '@kleekto/contracts';

import type { FormSnapshot } from './form-fill';

/**
 * Адаптер заполнения формы размещения (§6А.3).
 *
 * ПУБЛИКАЦИЯ — ОТДЕЛЬНАЯ СПОСОБНОСТЬ, а не расширение интерфейса чтения.
 * Источник может уметь читать объявления и не уметь заполнять форму: это два
 * разных куска чужой вёрстки, которые ломаются независимо. Поэтому и версии
 * разные — `parserVersion` у чтения, `formVersion` здесь.
 *
 * ЧТО АДАПТЕР НЕ ДЕЛАЕТ НИКОГДА (правило 12): не отправляет форму, не нажимает
 * «Опубликовать», не ставит галочку согласия, не решает капчу, не работает
 * в фоне и не поднимает объявления. Кнопку нажимает агент.
 */
export interface ListingPublishAdapter {
  readonly sourceId: string;

  /** Версионируется отдельно от `parserVersion`: ломаются они порознь. */
  readonly formVersion: string;

  canHandleForm(url: string): boolean;

  /**
   * Мы точно на форме СОЗДАНИЯ объявления, а не редактирования.
   *
   * Разница дорогая: заполнить форму редактирования чужого объявления значит
   * молча переписать его данные.
   */
  isNewListingForm(document: Document): boolean;

  /**
   * Заполняет поля, для которых есть данные, и честно перечисляет остальные.
   *
   * Частичное заполнение — штатный режим (правило 14), а не деградация.
   * Придуманных и «ближайших похожих» значений в форме не бывает: пустое поле
   * честнее неверного, потому что неверное агент не заметит и опубликует.
   */
  fill(document: Document, draft: ListingPublishDraft): FillOutcome;

  /** Распознанное созданное объявление либо `null` (§6А.7). */
  detectPublished(document: Document, url: string): PublishedRef | null;
}

/**
 * Результат заполнения плюс снимок формы.
 *
 * Снимок отделён от `FillResult`: наружу, на сервер, уходит только отчёт
 * (`FillResult`), а снимок держит ссылки на живые элементы страницы и
 * существует, пока открыта вкладка.
 */
export interface FillOutcome {
  result: FillResult;
  snapshot: FormSnapshot;
}

