import { z } from 'zod';

/**
 * Ответ health-эндпоинта.
 *
 * Намеренно проверяет базу, а не отвечает 200 безусловно: эндпоинт, который
 * всегда зелёный, не отвечает ни на один вопрос. `database: 'down'` даёт 503 —
 * приложение живо, но работать не может.
 */
export const healthResponseSchema = z.object({
  status: z.enum(['ok', 'degraded']),
  database: z.enum(['up', 'down']),
  /**
   * Настроено ли хранилище файлов.
   *
   * ЗДЕСЬ, А НЕ В ЛОГАХ, ПОТОМУ ЧТО СПРАШИВАЮТ СНАРУЖИ. «Не грузятся
   * фотографии» — это либо не заданные переменные окружения, либо что-то
   * совсем другое, и различить эти два случая без доступа к машине иначе
   * нельзя: отказ приходит агенту в браузер одной и той же надписью.
   *
   * Только «да» или «нет». Ни адреса, ни имени бака, ни тем более ключей:
   * эндпоинт открыт без аутентификации.
   *
   * Состояние приложения от этого не зависит: без хранилища продукт
   * работает, просто без загрузки картинок, — поэтому `status` остаётся
   * `ok`, а не становится `degraded`.
   */
  storage: z.enum(['ready', 'unconfigured']),
  /**
   * Имена незаданных переменных хранилища. Только при `unconfigured`.
   *
   * Имена, никогда значения — как и у ошибки базы. Иначе «не грузятся
   * фотографии» на чужой машине решается перебором пяти переменных.
   */
  storageMissing: z.array(z.string()).optional(),
  /** Версия приложения из package.json — чтобы видеть, что развёрнуто. */
  version: z.string(),
  checkedAt: z.string().datetime(),
  /** Время ответа базы в миллисекундах. Отсутствует, если база недоступна. */
  databaseLatencyMs: z.number().nonnegative().optional(),
  /**
   * Почему база недоступна. Только при `database: 'down'`.
   *
   * ИМЯ КЛАССА ОШИБКИ И ФЛАГИ, НИКОГДА ТЕКСТ. Сообщение Prisma содержит строку
   * подключения вместе с паролем, а эндпоинт открыт без аутентификации.
   * Имени класса достаточно, чтобы различить три случая, которые лечатся
   * по-разному: переменная не задана, хост недостижим, доступ отклонён.
   */
  databaseError: z
    .object({
      kind: z.string(),
      /** Разобранная причина: `env_missing`, `url_malformed`, `unreachable` и так далее. */
      reason: z.string(),
      /** Задана ли `DATABASE_URL`. Отличает «не настроено» от «не достучались». */
      urlConfigured: z.boolean(),
    })
    .optional(),
});

export type HealthResponse = z.infer<typeof healthResponseSchema>;
