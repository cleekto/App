import type { AuthContext } from '../auth/context';

/**
 * Какие фотографии объект принимает от браузера.
 *
 * Правила две, потому что случаи разные: у нового объекта своей истории ещё
 * нет, у существующего — есть, и в ней лежат внешние адреса с площадок.
 */

/** Больше двадцати снимков карточка всё равно не показывает. */
const MAX_PHOTOS = 20;

/**
 * Отсеивает ключи, не принадлежащие компании.
 *
 * Ключ приходит от браузера, и без проверки объект можно было бы завести
 * с фотографией из хранилища другого агентства. Молча отсеиваем, а не
 * отказываем: чужой ключ — это не ошибка агента, а попытка, и терять из-за
 * неё весь объект незачем.
 */
export function ownKeys(ctx: AuthContext, keys: string[] | undefined): string[] {
  if (keys === undefined) return [];
  return keys.filter((key) => key.startsWith(`${ctx.companyId}/`)).slice(0, MAX_PHOTOS);
}

/**
 * Что принимается в список фотографий при правке.
 *
 * СВОИ КЛЮЧИ ХРАНИЛИЩА — да. УЖЕ ЛЕЖАЩИЕ У ЭТОГО ОБЪЕКТА адреса — тоже:
 * иначе фотографии, пришедшие с площадки, нельзя было бы ни переставить,
 * ни убрать, потому что они внешние.
 *
 * А НОВЫЙ внешний адрес — нет. Иначе правкой объекта в карточку агентства
 * подставлялась бы любая картинка из интернета: браузер сходил бы за ней
 * на чужой сервер, и тот увидел бы, кто и когда смотрит объект.
 *
 * Отсеивается молча, как и при заведении: лишний ключ — не ошибка агента,
 * и терять из-за него всю правку незачем.
 */
export function keepablePhotos(ctx: AuthContext, next: string[], current: string[]): string[] {
  const known = new Set(current);
  return next
    .filter((key) => key.startsWith(`${ctx.companyId}/`) || known.has(key))
    .slice(0, MAX_PHOTOS);
}
