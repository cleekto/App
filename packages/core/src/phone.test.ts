import { describe, expect, it } from 'vitest';

import { ValidationError } from './errors';
import { maskPhone, normalizePhone } from './phone';

/**
 * Нормализация телефонов — самое вероятное место тихой поломки дедупликации
 * (риск R-06). Всё выглядит рабочим, а уровни 2–3 не срабатывают.
 *
 * Набор форматов здесь покрывает то, что вводит человек. Форматы со страниц
 * площадок неизвестны — это Q18, он ждёт фикстур фазы 5, и тогда эти тесты
 * дополняются реальными примерами, а не догадками.
 */
describe('нормализация телефона', () => {
  it.each([
    ['+995 555 12 34 56', '+995555123456'],
    ['+995555123456', '+995555123456'],
    ['995 555 123 456', '+995555123456'],
    ['0555 12 34 56', '+995555123456'],
    ['555123456', '+995555123456'],
    ['(555) 12-34-56', '+995555123456'],
    ['  +995-555-123-456  ', '+995555123456'],
  ])('%s → %s', (input, expected) => {
    expect(normalizePhone(input).normalized).toBe(expected);
  });

  it('оригинал сохраняется как ввели', () => {
    // Без оригинала разобраться в неверной нормализации будет невозможно,
    // а неверная нормализация ломает дедупликацию молча.
    const result = normalizePhone('  +995 555 12 34 56  ');
    expect(result.original).toBe('+995 555 12 34 56');
    expect(result.normalized).toBe('+995555123456');
  });

  it('разные записи одного номера дают один нормализованный вид', () => {
    // Это и есть смысл нормализации: ключ дедупликации уровней 2 и 3.
    const forms = ['+995 555 12 34 56', '0555123456', '555 12 34 56', '995555123456'];
    const normalized = new Set(forms.map((form) => normalizePhone(form).normalized));
    expect(normalized.size).toBe(1);
  });

  it.each([
    ['', 'пустая строка'],
    ['не телефон', 'нет цифр'],
    ['12345', 'слишком короткий'],
    ['+995 555 12 34 56 78', 'слишком длинный'],
    ['+1 202 555 0100', 'не грузинский номер'],
  ])('%s отклоняется (%s)', (input) => {
    // Номер, который не разобрался, — ошибка ввода, а не повод записать
    // в базу мусор, который потом сломает сравнение.
    expect(() => normalizePhone(input)).toThrow(ValidationError);
  });
});

describe('маскирование (правило 10)', () => {
  it('скрывает середину номера', () => {
    const masked = maskPhone('+995555123456');
    expect(masked).not.toContain('555123');
    expect(masked).toContain('995');
    expect(masked).toContain('56');
  });

  it('короткая строка маскируется целиком', () => {
    expect(maskPhone('12')).toBe('***');
  });
});
