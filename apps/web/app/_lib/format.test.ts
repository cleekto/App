import { LOCALES } from '@kleekto/i18n';
import { describe, expect, it } from 'vitest';

import { statusLabel } from './format';

describe('названия статусов воронки', () => {
  /**
   * Статусы создаются при регистрации компании — по-английски, потому что
   * язык компании в этот момент ещё не известен. Грузинский агент видел
   * «In base» и «Offered to client» посреди грузинского интерфейса, а это
   * самые частые надписи в CRM. Найдено ручным проходом по продукту.
   */
  it.each([
    ['ka', 'IN_BASE', 'ბაზაში'],
    ['ru', 'IN_BASE', 'В базе'],
    ['en', 'IN_BASE', 'In base'],
    ['ka', 'ARCHIVED', 'არქივი'],
    ['ru', 'OFFERED', 'Предложен клиенту'],
  ] as const)('на языке %s код %s читается как «%s»', (locale, code, expected) => {
    expect(statusLabel(locale, { code, name: 'In base' })).toBe(expected);
  });

  /**
   * ГЛАВНОЕ В ЭТОМ ПОДХОДЕ.
   *
   * Компания вправе завести свой статус (инвариант 4). Перевода у него нет
   * и быть не может, и подставлять вместо него что-либо — значит затирать
   * текст, который человек сам же и вписал. Показывается ровно имя.
   */
  it('свой статус компании остаётся с её именем', () => {
    expect(statusLabel('ka', { code: 'SHOWN_TWICE', name: 'Показан дважды' })).toBe(
      'Показан дважды',
    );
  });

  /**
   * И никакой видимой дыры `⟦ключ⟧`: она уместна там, где ключ известен
   * заранее и его отсутствие означает недоделку. Здесь ключ приходит
   * из данных, и дыра была бы ошибкой, а не честной пометкой.
   */
  it('у неизвестного кода не появляется метка непереведённого', () => {
    const label = statusLabel('ru', { code: 'ЧТО_УГОДНО', name: 'Моё название' });

    expect(label).not.toContain('⟦');
    expect(label).toBe('Моё название');
  });

  it('переведены все пять статусов, создаваемых при регистрации', () => {
    // Если статус добавят в набор по умолчанию и забудут перевести, агент
    // увидит английское слово среди грузинских — тест ловит это раньше него.
    for (const code of ['IN_BASE', 'IN_PROGRESS', 'OFFERED', 'CLOSED', 'ARCHIVED']) {
      for (const locale of LOCALES) {
        const label = statusLabel(locale, { code, name: 'НЕ ДОЛЖНО ПОКАЗАТЬСЯ' });
        expect(label, `${locale}/${code}`).not.toBe('НЕ ДОЛЖНО ПОКАЗАТЬСЯ');
      }
    }
  });
});
