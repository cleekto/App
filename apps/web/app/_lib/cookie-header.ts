/**
 * Подстановка одной куки в сырой заголовок `Cookie`.
 *
 * Нужна только `middleware.ts`. После тихого обновления сессии страница
 * внутри ТОГО ЖЕ запроса должна увидеть уже новый access-токен — иначе
 * агента на мгновение отправит на страницу входа, ещё до того как браузер
 * получит новый `Set-Cookie` и повторит запрос сам. Next даёт заменить
 * заголовки исходящего запроса только целиком, а не одну куку в них,
 * поэтому нужна эта строковая операция.
 *
 * Чистая функция ради теста без Next и без сети — как `form-fill.ts`
 * в расширении не знает о конкретной площадке, эта не знает о `NextRequest`.
 */
export function withCookie(header: string | null, name: string, value: string): string {
  const kept = (header ?? '')
    .split(';')
    .map((part) => part.trim())
    .filter((part) => part !== '' && part.split('=', 1)[0] !== name);

  kept.push(`${name}=${value}`);
  return kept.join('; ');
}
