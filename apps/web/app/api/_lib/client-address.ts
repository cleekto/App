/**
 * Адрес клиента для ограничения частоты запросов.
 *
 * За обратным прокси (Vercel) настоящий адрес приходит заголовком.
 * `x-forwarded-for` может содержать цепочку — берём первый элемент,
 * это клиент.
 *
 * ЗАГОЛОВОК ПОДДЕЛЫВАЕМ, и это надо понимать. За доверенным прокси он
 * достоверен, при прямом доступе к серверу — нет. Поэтому ограничение
 * по адресу здесь не единственное: параллельно считается предел на адрес
 * почты, который подделать нельзя, не отказавшись от самой попытки входа.
 */
export function clientAddress(request: Request): string {
  const forwarded = request.headers.get('x-forwarded-for');
  if (forwarded !== null && forwarded.trim() !== '') {
    return (forwarded.split(',')[0] ?? '').trim();
  }

  return request.headers.get('x-real-ip') ?? 'unknown';
}
