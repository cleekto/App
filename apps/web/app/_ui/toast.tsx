'use client';

import { Toaster as SonnerToaster, toast } from 'sonner';

/**
 * Уведомления о результате действия.
 *
 * КОГДА ПОКАЗЫВАТЬ, А КОГДА НЕТ — здесь это правило, а не вкус.
 *
 * Уведомление показывается, если результат действия НЕ ВИДЕН на экране
 * или если действие не удалось. Перетащенная карточка переехала у человека
 * на глазах — сообщать ему об этом нечего, а всплывающая плашка на каждое
 * перетаскивание за день превратится в помеху. Зато отказ сервера обязан
 * быть сказан вслух: молча вернувшаяся назад карточка читается как поломка
 * продукта, а не как «вам нельзя».
 *
 * Отсюда и набор: `notifyError` — всегда, `notifyDone` — только для того,
 * чего на экране не увидеть.
 *
 * СТРОКИ СЮДА ПРИХОДЯТ ГОТОВЫМИ. Ни одного слова в этом файле нет: текст
 * берётся из словаря на месте вызова (правило 18). Sonner о языках не знает
 * и знать не должен.
 *
 * Обёртка нужна и ради второго: если библиотеку когда-нибудь заменят,
 * менять придётся один файл, а не каждый обработчик в продукте.
 */

/** Ошибка. Живёт дольше успеха: её нужно успеть прочитать. */
export function notifyError(message: string): void {
  toast.error(message, { duration: 6000 });
}

/** Успех — только когда результат не виден на экране сам по себе. */
export function notifyDone(message: string): void {
  toast.success(message, { duration: 3000 });
}

/**
 * Место, где появляются уведомления. Монтируется ОДИН раз, в корневой
 * разметке: второй такой же дублировал бы каждое сообщение.
 *
 * Снизу справа, а не сверху: сверху у нас заголовок страницы и действия
 * раздела, и плашка перекрывала бы ровно то, после нажатия на что
 * она появилась.
 */
export function Toaster() {
  return (
    <SonnerToaster
      position="bottom-right"
      // Отступ от края — тот же, что у остального интерфейса.
      offset={16}
      // Цветная заливка по типу сообщения: ошибку надо отличать от успеха
      // мгновенно и не читая.
      richColors
      toastOptions={{
        style: {
          borderRadius: 'var(--radius-card)',
          fontFamily: 'var(--font-sans)',
        },
      }}
    />
  );
}
