import { describe, expect, it } from 'vitest';

import { fit, rename } from './compress';

/**
 * Само сжатие живёт в браузере — там холст и кодировщик, и в Node его
 * не проверить. Но решения, от которых зависит результат, — чистые, и вот
 * они проверяются: во что превращается размер и во что превращается имя.
 */

describe('пересчёт размера', () => {
  it('длинная сторона доводится ровно до предела', () => {
    expect(fit(4000, 3000, 1920)).toEqual({ width: 1920, height: 1440 });
    expect(fit(3000, 4000, 1920)).toEqual({ width: 1440, height: 1920 });
  });

  it('пропорции сохраняются', () => {
    const { width, height } = fit(4032, 3024, 1920);
    expect(width / height).toBeCloseTo(4032 / 3024, 2);
  });

  it('снимок меньше предела не растягивается', () => {
    // Увеличение не добавит подробностей, зато добавит веса — ровно наоборот
    // задаче.
    expect(fit(800, 600, 1920)).toEqual({ width: 800, height: 600 });
    expect(fit(1920, 1080, 1920)).toEqual({ width: 1920, height: 1080 });
  });

  it('очень вытянутая картинка не схлопывается в ноль', () => {
    // Панорама 10000×50 при округлении дала бы высоту 0 и пустой холст.
    const { height } = fit(10000, 50, 512);
    expect(height).toBeGreaterThanOrEqual(1);
  });

  it('квадрат остаётся квадратом', () => {
    expect(fit(3000, 3000, 512)).toEqual({ width: 512, height: 512 });
  });
});

describe('переименование', () => {
  it('расширение отражает новое содержимое', () => {
    // «договор.jpg», внутри которого WebP, обманет и человека, и программу,
    // которой он этот файл отдаст.
    expect(rename('IMG_4821.jpg')).toBe('IMG_4821.webp');
    expect(rename('план квартиры.PNG')).toBe('план квартиры.webp');
  });

  it('имя сохраняется целиком, включая точки внутри', () => {
    expect(rename('дом.вид.с.улицы.jpeg')).toBe('дом.вид.с.улицы.webp');
  });

  it('имя без расширения просто получает его', () => {
    expect(rename('снимок')).toBe('снимок.webp');
  });

  it('скрытый файл без расширения не теряет имени', () => {
    // Точка в начале — это не расширение, и обрезать по ней нельзя.
    expect(rename('.фото')).toBe('.фото.webp');
  });
});
